-- FEAT-SHARE-01: one public, shareable page per match (countdown → live →
-- summary) behind a random token.
--
-- * match_shares holds the coach's choices for one match. A row exists only
--   while at least one of «Del live» / «Del oppsummering» is on; turning both
--   off deletes it, so the old link stops working at once. Turning sharing on
--   again makes a new token.
-- * The token is 32 random bytes in base64url (43 characters). There is no
--   listing: the only way in is get_public_match_share(token).
-- * get_public_match_share runs as the owner (security definer) because
--   visitors are anonymous, and it is the only public read path. Everything a
--   detail level hides is filtered out here, in the database, so it never
--   reaches the browser or the server's response. Playing time, attendance,
--   lineup, notes and the internal AI report are never returned.
-- * The public summary text (public_summary_*) is generated by the server from
--   this function's own output and stored with the level it was made for and
--   a fingerprint of the data it was made from (public_summary_basis). It is
--   only returned while that level is still the share's level and the
--   fingerprint still matches the current data (goals or result corrected
--   since: 'pending', text null), so an old text is never shown as current,
--   not even to a visitor who calls the function directly. The fingerprint
--   rule is match_share_summary_basis below; publicSummaryBasis in
--   src/domain/matchShare.ts is the same rule, and the server checks it again.
-- * The result is the match's own score (score_for / score_against), the same
--   number the app shows. Goal events are the timeline only and may be
--   incomplete for older matches.
-- * matches.discarded_at marks a planned placeholder the coach discarded on
--   purpose (a new match shared in setup, then «Forkast og start nytt»). The
--   row and its data stay; lists leave it out, so it is never shown as a
--   coming match.
--
-- * Kick-off: a share made from a planned match uses the match's own time
--   (kickoff_from_match). A share made for a new match in setup has its own,
--   optional kickoff_at instead: the match row needs a starts_at, but that
--   placeholder is never shown as the kick-off. Without one the page says
--   «Venter på avspark» until the match starts, then shows when it started.
--
-- NOT APPLIED. Review, then apply with explicit approval.

begin;

create table if not exists public.match_shares (
  match_id uuid primary key references public.matches(id) on delete cascade,
  team_id uuid not null references public.teams(id) on delete cascade,
  token text not null,
  share_live boolean not null default false,
  share_summary boolean not null default false,
  detail_level text not null default 'status',
  age_group text not null default 'unknown',
  kickoff_from_match boolean not null default true,
  kickoff_at timestamptz,
  public_summary_text text,
  public_summary_level text,
  public_summary_generated_at timestamptz,
  public_summary_basis text,
  created_by uuid not null default auth.uid() references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint match_shares_token_format check (token ~ '^[A-Za-z0-9_-]{43}$'),
  constraint match_shares_token_unique unique (token),
  constraint match_shares_enabled check (share_live or share_summary),
  constraint match_shares_detail_level_check check (detail_level in ('status', 'result', 'detailed')),
  constraint match_shares_age_group_check check (age_group in ('child', 'youth', 'unknown')),
  -- v1: names are never public for children (12 and under) or an unknown age.
  constraint match_shares_names_need_youth check (detail_level <> 'detailed' or age_group = 'youth'),
  constraint match_shares_summary_level_check check (
    public_summary_level is null or public_summary_level in ('status', 'result', 'detailed')
  )
);

alter table public.matches add column if not exists discarded_at timestamptz;

create index if not exists idx_match_shares_team_id on public.match_shares(team_id);

drop trigger if exists set_match_shares_updated_at on public.match_shares;
create trigger set_match_shares_updated_at
before update on public.match_shares
for each row
execute function public.set_updated_at();

alter table public.match_shares enable row level security;

-- Team members manage their own matches' shares. Visitors have no table
-- access at all (no policy for anon); they only get the function below.

drop policy if exists "match_shares_select_member" on public.match_shares;
create policy "match_shares_select_member"
on public.match_shares
for select
to authenticated
using (public.is_team_member(team_id));

drop policy if exists "match_shares_insert_member" on public.match_shares;
create policy "match_shares_insert_member"
on public.match_shares
for insert
to authenticated
with check (
  public.is_team_member(team_id)
  and exists (
    select 1 from public.matches m where m.id = match_id and m.team_id = match_shares.team_id
  )
);

drop policy if exists "match_shares_update_member" on public.match_shares;
create policy "match_shares_update_member"
on public.match_shares
for update
to authenticated
using (public.is_team_member(team_id))
with check (
  public.is_team_member(team_id)
  and exists (
    select 1 from public.matches m where m.id = match_id and m.team_id = match_shares.team_id
  )
);

drop policy if exists "match_shares_delete_member" on public.match_shares;
create policy "match_shares_delete_member"
on public.match_shares
for delete
to authenticated
using (public.is_team_member(team_id));

revoke all on table public.match_shares from anon;

-- The public view of one shared match, or null for an unknown, malformed or
-- revoked token (the same answer for each, so a token cannot be probed).
--
-- Returned keys (nothing else):
--   phase            'upcoming' | 'live' | 'completed' (from the match status;
--                    a passed start time alone is still 'upcoming')
--   teamName, opponentName
--   startsAt         the match's time, or for a share made for a new match its
--                    own kickoff_at, else when the match started (null before)
--   shareLive, shareSummary, detailLevel
--   live             only while live and «Del live» is on: the clock basis and
--                    the time the coach's device last wrote (updatedAt)
--   score            level 'result' or 'detailed', while live with «Del live»
--                    on, and after the match: the match's score_for /
--                    score_against (authoritative)
--   goals            same levels: the goal timeline, minute + side only (may
--                    hold fewer goals than the score for older matches)
--   goals[].scorer / .assist
--                    level 'detailed' (youth only), own goals only
--   summary          after the match with «Del oppsummering» on:
--                    { status: 'ready' | 'pending', text, generatedAt, basis }
--                    'ready' only while the stored level and fingerprint match
--                    the answer itself (basis: checked again by the server,
--                    then dropped)

-- The summary fingerprint: one rule, here and in publicSummaryBasis
-- (src/domain/matchShare.ts); keep them identical. Input is the public answer
-- without its summary. Parts, joined with '|':
--   detailLevel, teamName ('' when missing), opponentName, startsAt,
--   score as 'for|against' (or one null), the goal count, then for each goal
--   minute, side, scorer, assist.
-- A string is ' followed by the text with \ and | escaped by \; an empty
-- opponent, scorer or assist counts as null; null is ~; a number is its whole,
-- non-negative decimal value. Hash: 32-bit FNV-1a over the UTF-8 bytes, as
-- 'v2:' and 8 lowercase hex digits (a change detector, not a secret).
create or replace function public.match_share_basis_text(p_value text)
returns text
language sql
immutable
set search_path = public
as $$
  select case when p_value is null then '~'
    else '''' || replace(replace(p_value, '\', '\\'), '|', '\|') end
$$;

create or replace function public.match_share_basis_whole(p_value text)
returns text
language sql
immutable
set search_path = public
as $$
  select case when p_value is null then '~'
    else greatest(floor(p_value::numeric), 0)::bigint::text end
$$;

create or replace function public.match_share_summary_basis(p_view jsonb)
returns text
language plpgsql
immutable
set search_path = public
as $$
declare
  v_goals jsonb := case when jsonb_typeof(p_view -> 'goals') = 'array' then p_view -> 'goals' else '[]'::jsonb end;
  v_goal jsonb;
  v_parts text[];
  v_bytes bytea;
  v_hash bigint := 2166136261;
  i integer;
begin
  v_parts := array[
    public.match_share_basis_text(p_view ->> 'detailLevel'),
    public.match_share_basis_text(coalesce(p_view ->> 'teamName', '')),
    public.match_share_basis_text(nullif(p_view ->> 'opponentName', '')),
    public.match_share_basis_text(nullif(p_view ->> 'startsAt', ''))
  ];
  if jsonb_typeof(p_view -> 'score') = 'object' then
    v_parts := v_parts || array[
      public.match_share_basis_whole(p_view -> 'score' ->> 'for'),
      public.match_share_basis_whole(p_view -> 'score' ->> 'against')
    ];
  else
    v_parts := v_parts || '~'::text;
  end if;
  v_parts := v_parts || jsonb_array_length(v_goals)::text;
  for v_goal in select value from jsonb_array_elements(v_goals) loop
    v_parts := v_parts || array[
      public.match_share_basis_whole(v_goal ->> 'minute'),
      public.match_share_basis_text(v_goal ->> 'side'),
      public.match_share_basis_text(nullif(v_goal ->> 'scorer', '')),
      public.match_share_basis_text(nullif(v_goal ->> 'assist', ''))
    ];
  end loop;

  v_bytes := convert_to(array_to_string(v_parts, '|'), 'UTF8');
  for i in 0 .. length(v_bytes) - 1 loop
    v_hash := ((v_hash # get_byte(v_bytes, i)) * 16777619) % 4294967296;
  end loop;
  return 'v2:' || lpad(to_hex(v_hash), 8, '0');
end;
$$;

revoke all on function public.match_share_basis_text(text) from public, anon, authenticated;
revoke all on function public.match_share_basis_whole(text) from public, anon, authenticated;
revoke all on function public.match_share_summary_basis(jsonb) from public, anon, authenticated;

create or replace function public.get_public_match_share(p_token text)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_share public.match_shares;
  v_match public.matches;
  v_team_name text;
  v_phase text;
  v_live_visible boolean;
  v_show_score boolean;
  v_show_names boolean;
  v_state jsonb;
  v_result jsonb;
  v_goals jsonb;
begin
  if p_token is null or p_token !~ '^[A-Za-z0-9_-]{43}$' then
    return null;
  end if;

  select * into v_share from public.match_shares where token = p_token;
  if not found or not (v_share.share_live or v_share.share_summary) then
    return null;
  end if;

  select * into v_match from public.matches where id = v_share.match_id;
  if not found then
    return null;
  end if;

  select name into v_team_name from public.teams where id = v_match.team_id;

  v_phase := case v_match.status
    when 'live' then 'live'
    when 'completed' then 'completed'
    else 'upcoming'
  end;

  -- Live data only with «Del live»; with only «Del oppsummering» a running
  -- match is just «pågår». After the match the final status follows the level.
  v_live_visible := v_phase = 'live' and v_share.share_live;
  v_show_score := v_share.detail_level in ('result', 'detailed')
    and (v_live_visible or v_phase = 'completed');
  v_show_names := v_show_score and v_share.detail_level = 'detailed' and v_share.age_group = 'youth';

  v_result := jsonb_build_object(
    'phase', v_phase,
    'teamName', coalesce(v_team_name, ''),
    'opponentName', v_match.opponent_name,
    'startsAt', case
      when v_share.kickoff_from_match then v_match.starts_at
      else coalesce(v_share.kickoff_at, v_match.started_at)
    end,
    'shareLive', v_share.share_live,
    'shareSummary', v_share.share_summary,
    'detailLevel', v_share.detail_level
  );

  if v_live_visible then
    v_state := case when jsonb_typeof(v_match.runtime_state) = 'object' then v_match.runtime_state else null end;
    v_result := v_result || jsonb_build_object(
      'live', jsonb_build_object(
        'updatedAt', v_match.updated_at,
        'phase', v_state ->> 'phase',
        'status', v_state ->> 'status',
        'halves', v_state -> 'halves',
        'regularSecondsPerHalf', v_state -> 'regularSecondsPerHalf',
        'phaseStartedAtElapsedMs', v_state -> 'phaseStartedAtElapsedMs',
        'clock', case when jsonb_typeof(v_state -> 'clock') = 'object' then jsonb_build_object(
          'startedAtMs', v_state -> 'clock' -> 'startedAtMs',
          'pausedAtMs', v_state -> 'clock' -> 'pausedAtMs',
          'accumulatedPausedMs', v_state -> 'clock' -> 'accumulatedPausedMs',
          'isRunning', v_state -> 'clock' -> 'isRunning'
        ) else null end
      )
    );
  end if;

  if v_show_score then
    select coalesce(jsonb_agg(
             jsonb_build_object(
               'minute', e.minute,
               'side', case e.type when 'goal_for' then 'own' else 'opponent' end
             )
             || case when v_show_names and e.type = 'goal_for' then jsonb_build_object(
                  'scorer', coalesce(nullif(e.payload ->> 'primaryPlayerName', ''), scorer.name),
                  'assist', coalesce(nullif(e.payload ->> 'secondaryPlayerName', ''), assist.name)
                ) else '{}'::jsonb end
             order by e.timestamp_ms nulls last, e.minute nulls last, e.created_at
           ), '[]'::jsonb)
      into v_goals
      from public.match_events e
      left join public.players scorer
        on scorer.id = e.primary_player_id and scorer.team_id = v_match.team_id
      left join public.players assist
        on assist.id = e.secondary_player_id and assist.team_id = v_match.team_id
     where e.match_id = v_match.id
       and e.type in ('goal_for', 'goal_against');

    v_result := v_result || jsonb_build_object(
      'score', jsonb_build_object(
        'for', greatest(coalesce(v_match.score_for, 0), 0),
        'against', greatest(coalesce(v_match.score_against, 0), 0)
      ),
      'goals', v_goals
    );
  end if;

  if v_phase = 'completed' and v_share.share_summary then
    v_result := v_result || jsonb_build_object(
      'summary',
      case
        when v_share.public_summary_text is not null
         and v_share.public_summary_level = v_share.detail_level
         and v_share.public_summary_basis = public.match_share_summary_basis(v_result) then
          jsonb_build_object(
            'status', 'ready',
            'text', v_share.public_summary_text,
            'generatedAt', v_share.public_summary_generated_at,
            'basis', v_share.public_summary_basis
          )
        else jsonb_build_object('status', 'pending', 'text', null, 'generatedAt', null, 'basis', null)
      end
    );
  end if;

  return v_result;
end;
$$;

revoke all on function public.get_public_match_share(text) from public;
grant execute on function public.get_public_match_share(text) to anon, authenticated;

commit;
